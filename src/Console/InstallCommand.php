    private function ensureSeoDependencies(bool $installDeps): bool
    {
        $dependencies = $this->seoDependencies();
        $missing = $this->missingPackages($dependencies);

        if (empty($missing)) {
            return true;
        }

        $requireList = array_map(
            fn(string $package) => $package . ":" . $dependencies[$package],
            $missing,
        );

        if (!$installDeps) {
            $this->warn(
                "Missing SEO dependencies. Re-run with --install-deps to install them.",
            );
            $this->line("composer require " . implode(" ", $requireList));
            $this->newLine();

            return false;
        }

        $this->info("Installing SEO dependencies...");

        if (! $this->runComposerRequirePackages($requireList)) {
            $this->error("Failed to install SEO dependencies.");

            return false;
        }

        $this->newLine();

        return true;
    }

