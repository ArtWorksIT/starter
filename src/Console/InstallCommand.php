    /**
     * @param array<int, array<string, mixed>> $entries
     */
    private function formatSeoEntries(array $entries): string
    {
        $lines = [];

        foreach ($entries as $entry) {
            $lines[] = $this->formatSeoEntry($entry);
        }

        return implode("\n", $lines);
    }

    /**
     * @param array<string, mixed> $entry
     */
    private function formatSeoEntry(array $entry): string
    {
        $schema = $entry['meta_structure'] ?? null;
        $schemaLine = '';

        if (is_array($schema)) {
            $schemaList = array_is_list($schema) ? $schema : [$schema];
            $schemaValues = [];

            foreach ($schemaList as $schemaEntry) {
                if (is_array($schemaEntry)) {
                    $schemaJson = json_encode(
                        $schemaEntry,
                        JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT,
                    );

                    if ($schemaJson !== false) {
                        $schemaValues[] = $schemaJson;
                    }

                    continue;
                }

                if (is_string($schemaEntry) && $schemaEntry !== '') {
                    $schemaValues[] = $schemaEntry;
                }
            }

            if ($schemaValues !== []) {
                $schemaLine = "\n                'meta_structure' => " . var_export($schemaValues, true) . ',';
            }
        }

        if (is_string($schema) && $schema !== '') {
            $schemaLine = "\n                'meta_structure' => " . var_export([$schema], true) . ',';
        }

        return "            [\n"
            . "                'url' => '{$entry['url']}',\n"
            . "                'meta_title' => '{$entry['meta_title']}',\n"
            . "                'meta_description' => '{$entry['meta_description']}',\n"
            . "                // 'og_image' => public_path('{$this->starterSeoOgImagePath($entry['url'])}'),"
            . $schemaLine
            . "\n            ],";
    }


