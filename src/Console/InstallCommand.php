    private function ensureDatabaseSeederCalls(): void
    {
        $path = database_path('seeders/DatabaseSeeder.php');
        $filesystem = $this->filesystem();

        if (! $filesystem->exists($path)) {
            $this->warn('DatabaseSeeder not found. Skipping seeder registration.');

            return;
        }

        $contents = $filesystem->get($path);

        if (
            Str::contains($contents, 'StarterUserSeeder::class')
            && Str::contains($contents, 'StarterSeoSeeder::class')
        ) {
            return;
        }

        if (! preg_match('/^(\s*)public function run\(\): void/m', $contents, $indentMatches)) {
            $this->warn('Unable to locate DatabaseSeeder::run. Skipping seeder registration.');

            return;
        }

        $indent = $indentMatches[1] ?? '    ';
        $bodyIndent = $indent.'    ';
        $pattern = '/public function run\(\): void\s*\{(?P<body>.*?)\}/s';

        $updated = preg_replace_callback($pattern, function (array $matches) use ($bodyIndent, $indent): string {
            $body = $matches['body'];
            $needsUserSeeder = ! Str::contains($body, 'StarterUserSeeder::class');
            $needsSeoSeeder = ! Str::contains($body, 'StarterSeoSeeder::class');

            if (! $needsUserSeeder && ! $needsSeoSeeder) {
                return $matches[0];
            }

            $seeders = [];

            if ($needsUserSeeder) {
                $seeders[] = 'StarterUserSeeder::class';
            }

            if ($needsSeoSeeder) {
                $seeders[] = 'StarterSeoSeeder::class';
            }

            $callBlock = $bodyIndent.'$this->call(['."\n";

            foreach ($seeders as $seeder) {
                $callBlock .= $bodyIndent.'    '.$seeder.",\n";
            }

            $callBlock .= $bodyIndent.']);';
            $existingBody = ltrim($body, "\n");
            $newBody = $callBlock;

            if (trim($existingBody) !== '') {
                $newBody .= "\n".$existingBody;
            }

            return "public function run(): void {\n".$newBody."\n".$indent.'}';
        }, $contents, 1);

        if ($updated === null) {
            $this->warn('Failed to update DatabaseSeeder.');

            return;
        }

        $filesystem->put($path, $updated);
    }

