    /**
     * @return array<string, string|bool>
     */
    private function planFile(
        Filesystem $files,
        array $manifest,
        string $relativePath,
        string $contents,
        bool $force,
        bool $allowMarker,
        bool $alwaysWrite,
    ): array {
        if ($relativePath === "routes/web.php") {
            return $this->planWebRoutes(
                $files,
                $manifest,
                $relativePath,
                $contents,
            );
        }

        if ($alwaysWrite) {
            return $this->planAlwaysWrite($files, $relativePath, $contents);
        }

        $absolutePath = base_path($relativePath);
        $exists = $files->exists($absolutePath);
        $hash = hash("sha256", $contents);

        $manifestFiles = Arr::get($manifest, "files", []);
        $manifestHash = is_array($manifestFiles)
            ? $manifestFiles[$relativePath] ?? null
            : null;
        $isManaged = is_string($manifestHash);

        $markerAllowed =
            $allowMarker && $this->hasMarker($files, $absolutePath);

        if ($exists && !$isManaged && !$force) {
            return [
                "path" => $relativePath,
                "status" => "skipped",
                "reason" => "conflict",
                "hash" => $hash,
                "contents" => $contents,
                "exists" => $exists,
            ];
        }

        if ($exists && !$isManaged && $force && !$markerAllowed) {
            return [
                "path" => $relativePath,
                "status" => "skipped",
                "reason" => "missing-marker",
                "hash" => $hash,
                "contents" => $contents,
                "exists" => $exists,
            ];
        }

        if (
            $exists &&
            $isManaged &&
            $manifestHash === $hash &&
            $files->get($absolutePath) === $contents
        ) {
            return [
                "path" => $relativePath,
                "status" => "unchanged",
                "hash" => $hash,
                "contents" => $contents,
                "exists" => $exists,
            ];
        }

        return [
            "path" => $relativePath,
            "status" => $exists ? "update" : "create",
            "hash" => $hash,
            "contents" => $contents,
            "exists" => $exists,
        ];
    }

    /**
     * @return array<string, string|bool>
     */
    private function planWebRoutes(
        Filesystem $files,
        array $manifest,
        string $relativePath,
        string $contents,
    ): array {
        $absolutePath = base_path($relativePath);
        $exists = $files->exists($absolutePath);
        $hash = hash("sha256", $contents);

        if (!$exists) {
            return [
                "path" => $relativePath,
                "status" => "create",
                "hash" => $hash,
                "contents" => $contents,
                "exists" => $exists,
                "always_update" => true,
            ];
        }

        if ($files->get($absolutePath) === $contents) {
            return [
                "path" => $relativePath,
                "status" => "unchanged",
                "hash" => $hash,
                "contents" => $contents,
                "exists" => $exists,
                "always_update" => true,
            ];
        }

        return [
            "path" => $relativePath,
            "status" => "update",
            "hash" => $hash,
            "contents" => $contents,
            "exists" => $exists,
            "always_update" => true,
        ];
    }

    /**
     * @return array<string, string|bool>
     */
    private function planAlwaysWrite(
        Filesystem $files,
        string $relativePath,
        string $contents,
    ): array {
        $absolutePath = base_path($relativePath);
        $exists = $files->exists($absolutePath);
        $hash = hash("sha256", $contents);

        if ($exists && $files->get($absolutePath) === $contents) {
            return [
                "path" => $relativePath,
                "status" => "unchanged",
                "hash" => $hash,
                "contents" => $contents,
                "exists" => $exists,
            ];
        }

        return [
            "path" => $relativePath,
            "status" => $exists ? "update" : "create",
            "hash" => $hash,
            "contents" => $contents,
            "exists" => $exists,
        ];
    }

    /**
     * @param array<int, array<string, string|bool>> $plan
     * @return array<string, array<string>>
     */
    private function summarizePlan(array $plan): array
    {
        $summary = [
            "create" => [],
            "update" => [],
            "unchanged" => [],
            "skipped" => [],
        ];

        foreach ($plan as $item) {
            $status = $item["status"];

            if (!is_string($status) || !array_key_exists($status, $summary)) {
                continue;
            }

            $summary[$status][] = $item["path"];
        }

        return $summary;
    }

    /**
     * @param array<string, array<string>> $summary
     */
    private function displayPlanSummary(array $summary): void
    {
        foreach (
            [
                "create" => "Will create",
                "update" => "Will update",
                "unchanged" => "Unchanged",
                "skipped" => "Skipped",
            ]
            as $key => $label
        ) {
            $items = $summary[$key] ?? [];

            if (empty($items)) {
                continue;
            }

            $this->line($label . ":");
            foreach ($items as $path) {
                $this->line("  - " . $path);
            }
            $this->newLine();
        }
    }

    /**
     * @param array<int, array<string, string|bool>> $plan
     * @return array{written_files: array<string, string>, skipped: array<string, string>}
     */
    private function applyPlan(Filesystem $files, array $plan): array
    {
        $writtenFiles = [];
        $skipped = [];

        foreach ($plan as $item) {
            $status = $item["status"] ?? "skipped";
            $path = $item["path"];
            $contents = $item["contents"];
            $hash = $item["hash"];

            if (
                !is_string($path) ||
                !is_string($contents) ||
                !is_string($hash)
            ) {
                continue;
            }

            if (!in_array($status, ["create", "update"], true)) {
                if ($status === "skipped") {
                    $skipped[$path] = (string) ($item["reason"] ?? $status);
                }

                continue;
            }

            $absolutePath = base_path($path);
            $directory = dirname($absolutePath);

            if (!$files->isDirectory($directory)) {
                $files->makeDirectory($directory, 0755, true);
            }

            $files->put($absolutePath, $contents);
            $writtenFiles[$path] = $hash;
        }

        return [
            "written_files" => $writtenFiles,
            "skipped" => $skipped,
        ];
    }

    /**
     * @param array<int, array<string, string|array>> $pageEntries
     * @param array<string, string> $writtenFiles
     */
    private function writeManifest(
        array $pageEntries,
        array $writtenFiles,
        array $skipped,
    ): void {
        $filesystem = $this->filesystem();
        $manifestPath = $this->manifestPath();
        $directory = dirname($manifestPath);
        $existingManifest = $filesystem->exists($manifestPath)
            ? $filesystem->get($manifestPath)
            : null;

        if (!$filesystem->isDirectory($directory)) {
            $filesystem->makeDirectory($directory, 0755, true);
        }

        $manifest = [
            "package" => config("starter.package_name"),
            "version" => config("starter.version"),
            "generated_at" => new DateTimeImmutable()->format(
                DateTimeImmutable::ATOM,
            ),
            "pages" => collect($pageEntries)
                ->map(fn(array $entry) => implode(">", $entry["segments"]))
                ->all(),
            "files" => $this->mergeManifestFiles(
                $writtenFiles,
                $skipped,
                $existingManifest,
            ),
        ];

        $filesystem->put(
            $manifestPath,
            json_encode($manifest, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) .
                "\n",
        );
    }

    private function renderStub(string $path, array $replacements): string
    {
        $contents = $this->filesystem()->get($path);

        foreach ($replacements as $key => $value) {
            $contents = str_replace("{{ " . $key . " }}", $value, $contents);
        }

        return $contents;
    }

    /**
     * @param array<string, string> $writtenFiles
     * @param array<string, string> $skipped
     */
    private function mergeManifestFiles(
        array $writtenFiles,
        array $skipped,
        ?string $existingManifest,
    ): array {
        $existingFiles = [];

        if (is_string($existingManifest)) {
            $decoded = json_decode($existingManifest, true);
            $existingFiles = is_array($decoded)
                ? Arr::get($decoded, "files", []) ?? []
                : [];
        }

        if (!is_array($existingFiles)) {
            $existingFiles = [];
        }

        $keptFromExisting = Arr::except($existingFiles, array_keys($skipped));
        $keptFromExisting = Arr::except(
            $keptFromExisting,
            array_keys($writtenFiles),
        );

        return array_merge($keptFromExisting, $writtenFiles);
    }

    private function stubPath(string $path): string
    {
        return dirname(__DIR__, 2) . "/stubs/" . $path;
    }

    private function manifestPath(): string
    {
        return config("starter.manifest_path");
    }

    private function hasMarker(Filesystem $files, string $path): bool
    {
        if (!$files->exists($path)) {
            return false;
        }

        $contents = $files->get($path);

        return Str::contains($contents, "Generated by Starter Package");
    }

    private function filesystem(): Filesystem
    {
        if (!$this->filesystem instanceof Filesystem) {
            $this->filesystem = app(Filesystem::class);
        }

        return $this->filesystem;
    }
