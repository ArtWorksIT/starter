<?php

namespace Artworksit\Starter\Console;

use DateTimeImmutable;
use Illuminate\Console\Command;
use Illuminate\Filesystem\Filesystem;
use Illuminate\Support\Arr;
use Illuminate\Support\Str;
use Symfony\Component\Process\Process;

class InstallCommand extends Command
{
    private ?Filesystem $filesystem = null;

    private bool $pendingComposerScripts = false;

    /**
     * @var array<int, array<string, string|array>>
     */
    private array $pageEntries = [];

    private bool $installBlog = false;

    private bool $installCareers = false;

    private ?string $careersMode = null;

    protected $signature = "starter:install {--force : Overwrite files generated by Starter} {--dry-run : Show what would be generated without writing files} {--install-deps : Install required SEO dependencies automatically}";

    protected $description = "Scaffold website pages, routes, controller, and base Blade components.";

    public function handle(Filesystem $files): int
    {
        $this->filesystem = $files;

        $this->info("artworksit/starter: install");
        $this->newLine();

        $dryRun = (bool) $this->option("dry-run");
        $force = (bool) $this->option("force");
        $installDeps = (bool) $this->option("install-deps");

        $pagesInput = $this->ask(
            "Which static pages do you need? (comma separated, e.g., home, about, about>history, services, contact)",
            "home, about, services, contact",
        );

        $rawPages = collect(explode(",", (string) $pagesInput))
            ->map(fn(string $page) => trim($page))
            ->filter()
            ->values()
            ->all();

        [$pages, $addedHome] = $this->normalizePages($rawPages);
        $pageTree = $this->buildPageTree($pages);
        $pageEntries = $this->flattenPageTree($pageTree);
        $this->pageEntries = $pageEntries;

        $installSeo = $this->confirm(
            "Would you like to manage SEO/Meta tags via Filament?",
            false,
        );

        if ($installSeo && !$this->ensureSeoDependencies($installDeps)) {
            $this->newLine();

            return self::FAILURE;
        }

        $installBlog = $this->confirm("Include Blog module?", false);
        $this->installBlog = $installBlog;

        if ($installBlog && ! $this->ensureBlogDependencies($installDeps)) {
            $this->newLine();

            return self::FAILURE;
        }

        $installCareers = $this->confirm('Include Careers module?', false);
        $careersMode = $installCareers
            ? $this->choice('How should jobs work?', ['external', 'internal'], 'external')
            : null;
        $this->installCareers = $installCareers;
        $this->careersMode = $careersMode;

        if ($installCareers && $careersMode === 'internal' && ! $this->ensureCareersDependencies($installDeps)) {
            $this->newLine();

            return self::FAILURE;
        }

        $this->runPostComposerScripts(false);

        if ($installSeo || $installBlog || $installCareers) {
            $this->ensureFilamentPanel();
            $this->ensureFilamentTheme();
        }

        if ($installSeo || $installBlog || ($installCareers && $careersMode === 'internal')) {
            $this->ensureMediaLibrarySetup();
        }

        if ($installBlog) {
            $this->ensureTagsSetup();
        }

        $this->line("Dry run:  " . ($dryRun ? "yes" : "no"));
        $this->line("Force:    " . ($force ? "yes" : "no"));
        $this->line("SEO:      " . ($installSeo ? "yes" : "no"));
        $this->line("Blog:     " . ($installBlog ? "yes" : "no"));
        $this->line("Careers:  " . ($installCareers ? "yes" : "no"));
        $this->line("Deps:     " . ($installDeps ? "install" : "skip"));
        $this->newLine();

        if ($addedHome) {
            $this->comment("Note: added home page automatically.");
            $this->newLine();
        }

        $this->info("Pages:");
        foreach ($pageEntries as $entry) {
            $this->line(
                sprintf(
                    "  %-16s → %-14s → %s",
                    $entry["url"],
                    $entry["route_name"],
                    Str::after($entry["view_file"], "resources/views/"),
                ),
            );
        }

        $this->newLine();

        if ($dryRun) {
            $this->comment("Dry run — no files written.");
            $this->newLine();
        }

        $manifest = $this->loadManifest();
        $filesPlan = $this->buildFilesPlan(
            $manifest,
            $pageEntries,
            $force,
            $installSeo,
            $installBlog,
            $installCareers,
            $careersMode,
        );
        $planSummary = $this->summarizePlan($filesPlan);

        if ($dryRun) {
            $this->displayPlanSummary($planSummary);

            return self::SUCCESS;
        }

        $results = $this->applyPlan($files, $filesPlan);
        $this->displayPlanSummary($planSummary);
        $this->newLine();

        $this->removeWelcomeView();

        if (!empty($results["skipped"])) {
            $this->warn(
                "Some files were skipped due to conflicts. Use --force if safe to overwrite.",
            );
        }

        if (
            $installSeo &&
            array_key_exists(
                "resources/views/components/layout.blade.php",
                $results["skipped"],
            )
        ) {
            $this->warn(
                "Layout was not updated. Add <x-seo /> inside your <head> section to enable SEO tags.",
            );
        }

        if (
            $installSeo &&
            array_key_exists(
                "resources/views/components/seo.blade.php",
                $results["skipped"],
            )
        ) {
            $this->warn(
                "SEO component was not updated. Ensure resources/views/components/seo.blade.php exists.",
            );
        }

        $this->writeManifest(
            $pageEntries,
            $results["written_files"],
            $results["skipped"],
        );

        $this->ensureDatabaseSeederCalls();

        $this->seedStarterUser();

        if ($installSeo && $installBlog) {
            $this->seedBlogIndexSeo();
        }

        if ($installSeo && $installCareers) {
            $this->seedCareersIndexSeo();
        }

        if ($installSeo) {
            $this->seedStarterSeo();
        }

        $this->runPostComposerScripts(true);

        $this->info("Starter install complete.");

        return self::SUCCESS;
    }

    /**
     * @param string[] $pages
     * @return array{0: string[], 1: bool}
     */
    private function normalizePages(array $pages): array
    {
        $normalized = collect($pages)
            ->map(function (string $page): string {
                $segments = collect(explode(">", $page))
                    ->map(
                        fn(string $segment) => Str::of($segment)
                            ->kebab()
                            ->lower()
                            ->value(),
                    )
                    ->filter();

                return $segments->implode(">");
            })
            ->filter()
            ->unique()
            ->values()
            ->all();

        $addedHome = false;

        if (in_array("home", $normalized, true)) {
            $normalized = array_values(
                array_filter($normalized, fn(string $page) => $page !== "home"),
            );
        } else {
            $addedHome = true;
        }

        array_unshift($normalized, "home");

        return [$normalized, $addedHome];
    }

    /**
     * @param string[] $pages
     * @return array<string, array>
     */
    private function buildPageTree(array $pages): array
    {
        $tree = [];

        foreach ($pages as $page) {
            $segments = array_values(array_filter(explode(">", $page)));
            $node = &$tree;

            foreach ($segments as $segment) {
                if (!array_key_exists($segment, $node)) {
                    $node[$segment] = [];
                }

                $node = &$node[$segment];
            }
        }

        return $tree;
    }

    /**
     * @param array<string, array> $tree
     * @return array<int, array<string, string|array>>
     */
    private function flattenPageTree(array $tree): array
    {
        $entries = [];

        foreach ($tree as $key => $children) {
            $this->appendEntry($entries, [$key], $children);
        }

        return $entries;
    }

    /**
     * @param array<int, array<string, string|array>> $entries
     * @param string[] $segments
     * @param array<string, array> $children
     */
    private function appendEntry(
        array &$entries,
        array $segments,
        array $children,
    ): void {
        $entries[] = $this->buildEntry($segments);

        foreach ($children as $child => $grandChildren) {
            $this->appendEntry(
                $entries,
                array_merge($segments, [$child]),
                $grandChildren,
            );
        }
    }

    /**
     * @param string[] $segments
     * @return array<string, string|array>
     */
    private function buildEntry(array $segments): array
    {
        $routeName = implode(".", $segments);
        $viewSegments = $segments;

        $url = $segments[0] === "home" ? "/" : "/" . implode("/", $segments);

        $controllerMethod =
            $segments[0] === "home"
                ? "home"
                : Str::camel(implode(" ", $segments));

        return [
            "key" => $routeName,
            "segments" => $segments,
            "url" => $url,
            "route_name" => $routeName,
            "view" => "pages." . implode(".", $viewSegments),
            "view_file" =>
                "resources/views/pages/" .
                implode("/", $viewSegments) .
                ".blade.php",
            "controller_method" => $controllerMethod,
        ];
    }

    /**
     * @return array<string, mixed>
     */
    private function loadManifest(): array
    {
        $filesystem = $this->filesystem();
        $manifestPath = $this->manifestPath();

        if (!$filesystem->exists($manifestPath)) {
            return [];
        }

        $contents = $filesystem->get($manifestPath);
        $decoded = json_decode($contents, true);

        return is_array($decoded) ? $decoded : [];
    }

    /**
     * @param array<int, array<string, string|array>> $pageEntries
     * @return array<int, array<string, string>>
     */
    private function buildFilesPlan(
        array $manifest,
        array $pageEntries,
        bool $force,
        bool $installSeo,
        bool $installBlog,
        bool $installCareers,
        ?string $careersMode,
    ): array {
        $plan = [];
        $filesystem = $this->filesystem();

        $filesToGenerate = $this->generateFilesPayload(
            $pageEntries,
            $installSeo,
            $installBlog,
            $installCareers,
            $careersMode,
        );

        foreach ($filesToGenerate as $relativePath => $payload) {
            $plan[] = $this->planFile(
                $filesystem,
                $manifest,
                $relativePath,
                $payload["contents"],
                $force,
                $payload["allow_marker"] ?? false,
                $payload["always_write"] ?? false,
            );
        }

        return $plan;
    }

    /**
     * @param array<int, array<string, string|array>> $pageEntries
     * @return array<string, array{contents: string, allow_marker?: bool, always_write?: bool}>
     */
    private function generateFilesPayload(
        array $pageEntries,
        bool $installSeo,
        bool $installBlog,
        bool $installCareers,
        ?string $careersMode,
    ): array {
        $this->installBlog = $installBlog;
        $this->installCareers = $installCareers;
        $this->careersMode = $careersMode;
        $routes = collect($pageEntries)
            ->map(
                fn(array $entry) => sprintf(
                    "Route::get('%s', [WebsiteController::class, '%s'])->name('%s');",
                    $entry["url"],
                    $entry["controller_method"],
                    $entry["route_name"],
                ),
            )
            ->implode("\n");

        if ($this->installBlog) {
            $routes .= "\n\nrequire __DIR__.'/blog.php';";
        }

        if ($this->installCareers) {
            $routes .= "\n\nrequire __DIR__.'/careers.php';";
        }

        $routesStub = $this->stubPath("routes/starter.stub");
        $routesContents = $this->renderStub($routesStub, [
            "routes" => $routes,
        ]);

        $controllerMethods = collect($pageEntries)
            ->map(function (array $entry): string {
                return sprintf(
                    "    public function %s(): \\Illuminate\\View\\View\n    {\n        return view('%s');\n    }",
                    $entry["controller_method"],
                    $entry["view"],
                );
            })
            ->implode("\n\n");

        $controllerContents = $this->renderStub(
            $this->stubPath("controllers/WebsiteController.stub"),
            [
                "methods" => $controllerMethods,
            ],
        );

        $layoutContents = $this->renderStub(
            $this->stubPath("views/components/layout.stub"),
            [
                "slot" => '{{ $slot }}',
                "seo" => $installSeo ? "<x-seo />" : "<title>Starter</title>",
            ],
        );

        $headerContents = $this->renderStub(
            $this->stubPath("views/components/header.stub"),
            [
                "links" => $this->headerLinksMarkup($pageEntries, $installCareers),
            ],
        );

        $footerContents = $this->renderStub(
            $this->stubPath("views/components/footer.stub"),
            [
                "footerText" => "© " . date("Y") . " Starter",
            ],
        );

        $pageStub = $this->stubPath("views/pages/page.stub");
        $pageFiles = [];

        foreach ($pageEntries as $entry) {
            $pageFiles[$entry["view_file"]] = [
                "contents" => $this->renderStub($pageStub, [
                    "title" => Str::headline(
                        str_replace(".", " ", $entry["key"]),
                    ),
                ]),
            ];
        }

        $seoFiles = $installSeo ? $this->seoFilesPayload($layoutContents) : [];
        $blogFiles = $installBlog ? $this->blogFilesPayload() : [];
        $careersFiles = $installCareers ? $this->careersFilesPayload($careersMode) : [];

        $payload = [
            "routes/starter.php" => [
                "contents" => $routesContents,
                "allow_marker" => true,
            ],
            "routes/web.php" => [
                "contents" => $this->updateRoutesWebContents("routes/web.php"),
                "allow_marker" => false,
                "always_write" => true,
            ],
            "app/Http/Controllers/WebsiteController.php" => [
                "contents" => $controllerContents,
                "allow_marker" => true,
            ],
            "resources/views/components/layout.blade.php" => [
                "contents" => $layoutContents,
                "allow_marker" => true,
            ],
            "resources/views/components/header.blade.php" => [
                "contents" => $headerContents,
                "allow_marker" => true,
            ],
            "resources/views/components/footer.blade.php" => [
                "contents" => $footerContents,
                "allow_marker" => true,
            ],
        ];

        $extras = array_merge($seoFiles, $blogFiles, $careersFiles);

        return array_merge($payload, $extras, $pageFiles);
    }

    private function updateRoutesWebContents(string $relativePath): string
    {
        $path = base_path($relativePath);
        $filesystem = $this->filesystem();
        $contents = $filesystem->exists($path)
            ? $filesystem->get($path)
            : "<?php\n";

        $contents = $this->removeDefaultWebRoute($contents);

        if (Str::contains($contents, "require __DIR__.'/starter.php';")) {
            return $contents;
        }

        $trimmed = rtrim($contents);

        return $trimmed . "\n\nrequire __DIR__.'/starter.php';\n";
    }

    private function removeDefaultWebRoute(string $contents): string
    {
        $pattern = "/Route::get\('\/',\s*function\s*\(\)\s*\{\s*return\s+view\('welcome'\);\s*\}\);/s";

        $updated = preg_replace($pattern, '', $contents);

        if (! is_string($updated)) {
            return $contents;
        }

        $updated = str_replace("use Illuminate\\Support\\Facades\\Route;\n\n\n", "use Illuminate\\Support\\Facades\\Route;\n\n", $updated);

        return trim($updated)."\n";
    }

    private function removeWelcomeView(): void
    {
        $path = resource_path('views/welcome.blade.php');
        $filesystem = $this->filesystem();

        if (! $filesystem->exists($path)) {
            return;
        }

        $filesystem->delete($path);
        $this->line('Removed default resources/views/welcome.blade.php');
    }

    /**
     * @param array<int, array<string, string|array>> $pageEntries
     */
    private function headerLinksMarkup(array $pageEntries, bool $installCareers): string
    {
        $links = [];

        foreach ($pageEntries as $entry) {
            $links[] = sprintf(
                '<a href="%s">%s</a>',
                $entry['url'],
                Str::headline(str_replace('.', ' ', $entry['key'])),
            );
        }

        if ($this->installBlog) {
            $links[] = "@if (Route::has('blog.index'))\n            <a href=\"{{ route('blog.index') }}\">Blog</a>\n        @endif";
        }

        if ($installCareers) {
            $links[] = "@if (Route::has('careers.index'))\n            <a href=\"{{ route('careers.index') }}\">Careers</a>\n        @endif";
        }

        return implode("\n        ", $links);
    }

    /**
     * @param array<int, array<string, string|array>> $pageEntries
     */
    private function starterSeoSeederEntries(array $pageEntries): string
    {
        $entries = [];

        foreach ($pageEntries as $entry) {
            $entries[] = sprintf(
                "            [\n                'url' => '%s',\n                'meta_title' => '%s',\n                'meta_description' => '%s',\n                // 'og_image' => public_path('%s'),\n                'meta_structure' => %s,\n            ],",
                $entry['url'],
                Str::headline(str_replace('.', ' ', $entry['key'])),
                $this->starterSeoDescription($entry),
                $this->starterSeoOgImagePath($entry['url']),
                $this->starterSeoSchema($entry),
            );
        }

        return implode("\n", $entries);
    }

    /**
     * @param array<string, string|array> $entry
     */
    private function starterSeoDescription(array $entry): string
    {
        $title = Str::headline(str_replace('.', ' ', $entry['key']));

        return $title.' page generated by Starter.';
    }

    /**
     * @param array<string, string|array> $entry
     */
    private function starterSeoSchema(array $entry): string
    {
        $title = Str::headline(str_replace('.', ' ', $entry['key']));
        $schema = [
            '@context' => 'https://schema.org',
            '@type' => 'WebPage',
            'name' => $title,
            'url' => $entry['url'],
        ];

        $schemaJson = json_encode($schema, JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);

        if ($schemaJson === false) {
            return '[]';
        }

        return var_export([$schemaJson], true);
    }

    private function starterSeoOgImagePath(string $url): string
    {
        $path = trim($url, '/');

        if ($path === '') {
            $path = 'home';
        }

        $path = Str::slug(str_replace('/', '-', $path));

        return 'og/'.$path.'.png';
    }

