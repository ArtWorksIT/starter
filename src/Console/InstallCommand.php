    /**
     * @param array<int, array<string, mixed>> $entries
     */
    private function addSeoSeederEntries(array $entries): void
    {
        $path = $this->starterSeoSeederPath();
        $filesystem = $this->filesystem();

        if (! $filesystem->exists($path)) {
            $this->warn('StarterSeoSeeder not found. Skipping SEO entry updates.');

            return;
        }

        $contents = $filesystem->get($path);

        $contents = preg_replace(
            '/^use Illuminate\\Database\\Console\\Seeds\\WithoutModelEvents;\R/m',
            '',
            $contents,
        );
        $contents = preg_replace('/^\s*use WithoutModelEvents;\R/m', '', $contents);

        if (! Str::contains($contents, 'Generated by Starter Package')) {
            $this->warn('StarterSeoSeeder does not appear to be managed by Starter. Skipping updates.');

            return;
        }

        $newEntries = [];

        foreach ($entries as $entry) {
            $url = $entry['url'] ?? null;

            if (! is_string($url) || $url === '') {
                continue;
            }

            $pattern = '/[\'\"]url[\'\"]\s*=>\s*[\'\"]' . preg_quote($url, '/') . '[\'\"]/';

            if (preg_match($pattern, $contents) === 1) {
                continue;
            }

            $newEntries[] = $entry;
        }

        if ($newEntries === []) {
            $this->line('StarterSeoSeeder already includes these SEO entries.');

            return;
        }

        $formatted = $this->formatSeoEntries($newEntries);
        $pattern = '/(\$entries\s*=\s*\[)(.*?)(\n\s*\];)/s';

        if (! preg_match($pattern, $contents)) {
            $this->warn('Unable to locate entries array in StarterSeoSeeder. Skipping updates.');

            return;
        }

        $updated = preg_replace_callback($pattern, function (array $matches) use ($formatted): string {
            $body = rtrim($matches[2]);
            $body = $body === '' ? '' : $body . "\n";
            $body .= rtrim($formatted);

            return $matches[1] . $body . $matches[3];
        }, $contents, 1);

        if ($updated === null) {
            $this->warn('Failed to update StarterSeoSeeder.');

            return;
        }

        $filesystem->put($path, $updated);
        $this->info('StarterSeoSeeder updated with additional SEO entries.');
    }

